/**
 * Sync DATABASE_URL (+ auth) from repo root .env → app .env.local files.
 * Run: npm run supabase:sync-env
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env");
if (!existsSync(envPath)) {
  console.error("Missing .env in repo root");
  process.exit(1);
}

const env = readFileSync(envPath, "utf8");

function pick(name) {
  const m = env.match(new RegExp(`^${name}="([^"]*)"`, "m"));
  return m?.[1] ?? null;
}

const keys = [
  "DATABASE_URL",
  "DIRECT_URL",
  "AUTH_SECRET",
  "AUTH_URL",
  "NEXT_PUBLIC_PLATFORM_URL",
];

const picked = Object.fromEntries(keys.map((k) => [k, pick(k)]));
if (!picked.DATABASE_URL) {
  console.error("DATABASE_URL not found in .env");
  process.exit(1);
}

const targets = [
  join(root, "apps/merchant-admin/.env.local"),
  join(root, "apps/merchant-web/.env.local"),
];

const header = `# Auto-generated by npm run supabase:sync-env — do not edit DATABASE_URL manually\n`;
const body = keys
  .filter((k) => picked[k])
  .map((k) => `${k}="${picked[k]}"`)
  .join("\n");

for (const file of targets) {
  writeFileSync(file, `${header}${body}\n`, "utf8");
  console.log("Wrote", file);
}

console.log("\nDone. Restart npm run dev if apps were running.");
